"""4.Q.4 step 1: Fresh Release qualification for the 4.1 authority substrate proof.

This is a FRESH, INDEPENDENT experiment -- not a reuse of the archived
_env_release_record.pkl (experiment_id ENV-RELEASE, condition_signature_hash
2ad6168671cfac32). It uses the same production harness (serum2.evidence.harness)
that produced that record, with the same nominal stimulus for measurement
comparability, but the causal outcome here is NOT assumed. Per 4.Q.3 section 4:

    EFFECT_OBSERVED     -> contract may become CAUSAL_VERIFIED, continue 4.1
    NO_OBSERVED_EFFECT  -> contract becomes NEGATIVE_EVIDENCE, 4.1 STOPS

Do not edit this file to change the threshold or reinterpret the outcome after
seeing the result. That would exactly reproduce the mistake this qualification
exists to prevent.
"""
import sys, pickle
sys.path.insert(0, r"D:\ableton claude")
from serum2.evidence import harness
from serum2.evidence.spec import (ExperimentSpec, Mutation, Stimulus,
                                  MeasurementPlan, TargetSpec, SINGLE_FIELD)

spec = ExperimentSpec(
    experiment_id="release_qualified_complete_001",
    mutations=[Mutation("Env0.plainParams.kParamRelease", 1.0,
                        "4.Q.4 fresh qualification: absolute parameter value, "
                        "not a delta -- see mutation_value_semantics=ABSOLUTE_PARAMETER_VALUE")],
    prerequisites=[],
    baseline_overrides=[Mutation("Env0.plainParams.kParamDecay", 0.02,
                                 "shared context: short decay so both arms are fully settled "
                                 "before note-off, before the tail measurement window begins")],
    isolation_level=SINGLE_FIELD,
    claim_subject="Env1.Release",
    claim_predicate="extends",
    measurement_plans=[MeasurementPlan(
        metric="tail_rms_db",
        target=TargetSpec("Env0.plainParams.kParamRelease", "Env", "kParamRelease"),
        expected_direction="increase",
        threshold=1.0,
        stimulus=Stimulus(note=60, velocity=110, note_len=0.4, render_seconds=2.0, tail_start=0.6),
        kernel_artifact="tail_rms_db.py",
    )],
    notes="4.Q.4 FRESH qualification for 4.1 authority substrate proof. Stimulus and "
          "baseline_overrides chosen to match archived ENV-RELEASE "
          "(condition_signature_hash=2ad6168671cfac32) for measurement comparability, "
          "but this is an independent experiment run: the causal outcome is not assumed "
          "from that prior result.",
)

print("=" * 70)
print("4.Q.4 FRESH RELEASE QUALIFICATION -- experiment_id: %s" % spec.experiment_id)
print("=" * 70)

rec = harness.run(spec)

print("\ngate_completeness:", rec.gate_completeness())
m = rec.causal_measurements[0]
print("\nmeasurement_definition_id:", m.measurement_definition_id)
print("causal: baseline=%.4f treatment=%.4f delta=%+.4f threshold=%.2f" %
      (m.baseline, m.treatment, m.delta, m.threshold))
print("direction: expected=%s observed=%s" % (m.expected_direction, m.observed_direction))
print("STATUS:", m.status)
print("\npersistence:", rec.persistence_observation["status"],
      rec.persistence_observation.get("detail"))
print("\nexperiment_condition_signature:", rec.experiment["experiment_condition_signature"])

pickle.dump(rec, open(r"D:\ableton claude\experiments\_env_release_qualified_complete_001.pkl", "wb"))
print("\nSaved: experiments/_env_release_qualified_complete_001.pkl")

print("\n" + "=" * 70)
if m.status == "EFFECT_OBSERVED":
    print("OUTCOME: EFFECT_OBSERVED -- fresh qualification SUCCEEDS. Proceed to contract build.")
else:
    print("OUTCOME: %s -- fresh qualification FAILS. 4.1 STOPS HERE." % m.status)
    print("Do not build a CAUSAL_VERIFIED contract. Do not reuse the archived contract.")
print("=" * 70)
